// ---------------------------------------------------------
// Pricing helpers
// ---------------------------------------------------------

export function getPricingSummary(pricing) {
  if (!pricing) {
    return "Pricing information unavailable";
  }

  if (pricing.lifetime && pricing.recurring) {
    return "Subscription + lifetime option";
  }

  if (pricing.lifetime) {
    return "Lifetime / one-time option";
  }

  if (pricing.recurring) {
    return "Recurring subscription";
  }

  if (pricing.oneTime) {
    return "One-time / premium purchase";
  }

  return pricing.model || "See pricing";
}

